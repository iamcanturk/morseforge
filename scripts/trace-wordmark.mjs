/**
 * Trace the wordmark from the self-hosted display face into path data.
 *
 *   node scripts/trace-wordmark.mjs
 *
 * Writes src/components/brand/wordmarkOutline.ts: SITE.name ("MorseForge") in
 * Space Grotesk at weight 700, as one SVG path. The site then draws its name
 * from geometry with no font dependency: the header, the favicon generator,
 * the share cards and the OG images all get the same letters whether or not a
 * webfont has loaded. Rerun it if SITE.name, the font or the kerning changes;
 * mark.test.ts fails if the traced text and SITE.name disagree.
 */

import { writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { register } from 'node:module'

register(pathToFileURL(join(import.meta.dirname, 'ts-resolve.mjs')))

const { font, textPath } = await import('./brand-type.mjs')

const ROOT = resolve(import.meta.dirname, '..')
const { SITE } = await import(join(ROOT, 'src/config/site.ts'))

const WEIGHT = 700
/** Tracking in em, and pair kerning in font units (1000 per em), set by eye. */
const TRACKING = -0.012
const KERN = { Fo: -28, eF: 6, rs: -6, rg: -4 }
const OUT = join(ROOT, 'src/components/brand/wordmarkOutline.ts')

const f = font('grotesk', WEIGHT)
const CAP = f.capHeight
const text = SITE.name

// A cheap check that the instance really is wght 700: the M's left stem is
// about 64 units wide in the Light default and about 130 in the Bold.
const m = f.glyphForCodePoint('M'.codePointAt(0))
const mPoints = m.path.commands.flatMap(({ args }) => {
  const out = []
  for (let k = 0; k < args.length; k += 2) out.push([args[k], args[k + 1]])
  return out
})
const left = Math.min(...mPoints.map(([x]) => x))
const stem = Math.min(...mPoints.filter(([x, y]) => y === 0 && x > left).map(([x]) => x)) - left
if (stem < 110) throw new Error(`wght ${WEIGHT} did not apply (M stem ${stem} units)`)

// Lay out at 1 unit per font unit, baseline at y = CAP so the cap line is 0.
const laid = textPath(text, {
  family: 'grotesk',
  weight: WEIGHT,
  size: f.unitsPerEm,
  y: CAP,
  tracking: TRACKING,
  kern: KERN,
})

// Ink bounds, from the path's own coordinates (TrueType outlines keep their
// extremes on on-curve points, so control points do not overshoot).
const numbers = [...laid.d.matchAll(/-?[\d.]+/g)].map(([v]) => Number(v))
const xs = numbers.filter((_, i) => i % 2 === 0)
const ys = numbers.filter((_, i) => i % 2 === 1)
const minX = Math.min(...xs)
const r = (v) => Math.round(v * 10) / 10
const d = laid.d.replace(
  /(-?[\d.]+) (-?[\d.]+)/g,
  (_, x, y) => `${r(Number(x) - minX)} ${r(Number(y))}`,
)

const out = `/**
 * GENERATED by scripts/trace-wordmark.mjs. Do not edit; rerun the script.
 *
 * "${text}" (SITE.name) traced from public/fonts/space-grotesk-700.woff2 at
 * wght ${WEIGHT}, tracking ${TRACKING}em, kerning ${JSON.stringify(KERN).replace(/"/g, '')}.
 * Font units, y down: the cap line is y = 0 and the baseline y = capHeight.
 * The ink starts at x = 0 and ends at x = width.
 */
export const WORDMARK_OUTLINE = {
  text: '${text}',
  capHeight: ${CAP},
  width: ${r(Math.max(...xs) - minX)},
  /** Highest ink, above the cap line (negative), and lowest, below the baseline. */
  top: ${r(Math.min(...ys))},
  bottom: ${r(Math.max(...ys))},
  d: '${d}',
} as const
`
writeFileSync(OUT, out)
console.log(`wrote ${OUT}: ${d.length} chars, M stem ${stem} units`)
